def lines(s,width,size=11.5,bold=False):
    font='ArabicBold' if bold else 'Arabic'; out=[]; line=''
    for word in s.split():
        trial=(line+' '+word).strip()
        if line and pdfmetrics.stringWidth(shaped(trial),font,size)>width: out.append(line);line=word
        else:line=trial
    if line:out.append(line)
    return out
